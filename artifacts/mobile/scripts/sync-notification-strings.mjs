#!/usr/bin/env node
/**
 * Copies the website's NOTIFICATION strings into the app, so a notification
 * reads in the reader's own language on the phone too.
 *
 * The website writes notifications carrying translation keys — Manufacturing's
 * `mfn_*` events and Procurement's `pn_*` notices, in `Portal.Shared` of
 * messages/{ar,en}.json — plus text rendered in the SENDER's language as a
 * fallback. The website renders the keys; this app used to show only the
 * fallback, so an English reader got Arabic whenever an Arabic user acted.
 *
 *   node scripts/sync-notification-strings.mjs [websiteDir]          → writes i18n/notifications.generated.ts
 *   node scripts/sync-notification-strings.mjs [websiteDir] --check  → exit 1 if it is out of date
 *
 * websiteDir defaults to $MDMAK_WEB_DIR, then /home/shady/ora2/studio-monaqasati.
 */

import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const OUT = path.join(ROOT, "i18n", "notifications.generated.ts")
const check = process.argv.includes("--check")
const webDir = process.argv.slice(2).find((a) => !a.startsWith("--")) || process.env.MDMAK_WEB_DIR || "/home/shady/ora2/studio-monaqasati"
// mfn_* Manufacturing events · pn_* Procurement notices · the Sales and CRM
// notices (transfer notices, quote requests) and the labels their "@key"
// params point at (a decline reason).
const PREFIXES = ["mfn_", "pn_", "sales_tn_notif_", "sales_rq_notif_", "sales_rq_reason_", "crm_rq_notif_"]

function pick(lang) {
  const file = path.join(webDir, "messages", `${lang}.json`)
  const shared = JSON.parse(fs.readFileSync(file, "utf8")).Portal.Shared
  const out = {}
  for (const k of Object.keys(shared).sort()) if (PREFIXES.some((p) => k.startsWith(p)) && typeof shared[k] === "string") out[k] = shared[k]
  return out
}

const en = pick("en")
const ar = pick("ar")
const missing = Object.keys(en).filter((k) => !(k in ar)).concat(Object.keys(ar).filter((k) => !(k in en)))
if (missing.length) {
  console.error("keys present in one language only:", missing.join(", "))
  process.exit(1)
}

const body = `// GENERATED by scripts/sync-notification-strings.mjs from the website's
// messages/{ar,en}.json (Portal.Shared ${PREFIXES.map((p) => p + "*").join(", ")}). Do not edit —
// re-run the script. ${Object.keys(en).length} keys.

export const NOTIFICATION_STRINGS: Record<"en" | "ar", Record<string, string>> = ${JSON.stringify({ en, ar }, null, 2)}
`

if (check) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : ""
  if (current !== body) {
    console.error("i18n/notifications.generated.ts is out of date — run scripts/sync-notification-strings.mjs")
    process.exit(1)
  }
  console.log(`notification strings in sync (${Object.keys(en).length} keys)`)
} else {
  fs.writeFileSync(OUT, body)
  console.log(`wrote ${path.relative(ROOT, OUT)} — ${Object.keys(en).length} keys per language`)
}
